-- A received server-issued ID can have another device's incarnation check.
-- Remember its local ownership at removal, including rows imported before this upgrade.
CREATE TABLE IF NOT EXISTS removed_message_owners(id TEXT PRIMARY KEY, role TEXT NOT NULL);
CREATE TRIGGER IF NOT EXISTS remember_removed_message AFTER DELETE ON messages
WHEN OLD.id GLOB 'dc??????-????-8???-????-????????????' OR OLD.id GLOB 'notice-dc??????-????-8???-????-????????????'
BEGIN
    INSERT OR IGNORE INTO removed_message_owners VALUES(OLD.id, OLD.role);
END;
