#!/usr/bin/env python3
"""Regenerate crates/core/src/skills/bundled_manifest.rs from bundled/skills/.

Every file under the bundled skills tree is embedded as the installer source.
Entries are sorted by skill, then relative path, so the generated manifest and
the tree hash used by the installer are deterministic.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TREE = ROOT / "crates/core/src/skills/bundled/skills"
OUTPUT = ROOT / "crates/core/src/skills/bundled_manifest.rs"

entries = []
for path in sorted(TREE.rglob("*")):
    if not path.is_file():
        continue
    relative = path.relative_to(TREE)
    skill, inner = relative.parts[0], Path(*relative.parts[1:]).as_posix()
    entries.append((skill, inner, path.relative_to(OUTPUT.parent).as_posix()))

entries.sort()
lines = [
    "// Generated by scripts/generate_bundled_manifest.py from bundled/skills/.",
    "// Every bundled skill file is embedded here as the installer source.",
    "pub(crate) const FILES: &[(&str, &str, &[u8])] = &[",
]
for skill, inner, source in entries:
    lines.append(f'    ("{skill}", "{inner}", include_bytes!("{source}")),')
lines.append("];")
OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {len(entries)} entries to {OUTPUT}")
